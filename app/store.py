import json
from pathlib import Path

from .channel_feed import install_ops_feed
from .database import connect, enable_local_wal, is_postgres


def dump(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


class Store:
    def __init__(self, path, definitions):
        self.path = str(path)
        if not is_postgres(self.path):
            Path(self.path).parent.mkdir(parents=True, exist_ok=True)
        enable_local_wal(self.path)
        with self.connect(write=True) as conn:
            seq = ", record_seq BIGINT GENERATED BY DEFAULT AS IDENTITY" if conn.postgres else ""
            conn.executescript(f"""
            CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, title TEXT NOT NULL, ontology_id TEXT NOT NULL);
            CREATE TABLE IF NOT EXISTS objects (
                event_id TEXT NOT NULL, ontology_id TEXT NOT NULL, object_type TEXT NOT NULL,
                id TEXT NOT NULL, version INTEGER NOT NULL, data TEXT NOT NULL,
                PRIMARY KEY(event_id, ontology_id, object_type, id)
            );
            CREATE TABLE IF NOT EXISTS messages (id TEXT PRIMARY KEY, event_id TEXT NOT NULL, data TEXT NOT NULL{seq});
            CREATE TABLE IF NOT EXISTS proposals (id TEXT PRIMARY KEY, event_id TEXT NOT NULL, message_id TEXT NOT NULL, data TEXT NOT NULL{seq},
                UNIQUE(event_id, message_id));
            CREATE TABLE IF NOT EXISTS receipts (
                id TEXT PRIMARY KEY, event_id TEXT NOT NULL, idempotency_key TEXT NOT NULL, fingerprint TEXT NOT NULL,
                actor TEXT NOT NULL, data TEXT NOT NULL{seq}, UNIQUE(event_id,idempotency_key)
            );
            CREATE TABLE IF NOT EXISTS tak_deliveries (
                event_id TEXT NOT NULL, kind TEXT NOT NULL, operation_id TEXT NOT NULL,
                cot_uid TEXT NOT NULL UNIQUE, fingerprint TEXT NOT NULL, payload TEXT NOT NULL,
                status TEXT NOT NULL CHECK(status IN ('awaiting_readback','retryable','received')),
                recipient_uid TEXT NOT NULL, actor TEXT NOT NULL, created_at TEXT NOT NULL, received_at TEXT,
                PRIMARY KEY(event_id, kind, operation_id)
            );
            """)
            install_ops_feed(conn)
            for definition in definitions.values():
                for event in definition["events"]:
                    # Existing events are never reset by server restart or fixture changes.
                    if conn.execute("SELECT 1 FROM events WHERE id=?", (event["id"],)).fetchone():
                        continue
                    conn.execute("INSERT INTO events VALUES (?,?,?)", (event["id"], event["title"], definition["ontology_id"]))
                    for obj in event["objects"]:
                        conn.execute("INSERT INTO objects VALUES (?,?,?,?,?,?)", (event["id"], definition["ontology_id"], obj["object_type"], obj["id"], 1, dump(obj["data"])))

    def connect(self, write=False):
        return connect(self.path, write=write)

    @staticmethod
    def records(conn, table, event_id):
        # Table names are internal constants, never request values.
        if table not in {"messages", "proposals", "receipts"}:
            raise ValueError("Unsupported record collection")
        order = "record_seq" if conn.postgres else "rowid"
        return [json.loads(row["data"]) for row in conn.execute(f"SELECT data FROM {table} WHERE event_id=? ORDER BY {order}", (event_id,))]
